CREATE OR REPLACE PROCEDURE ACTUALIZAR_UNIDAD_EQUIPO (
    p_id_unidad NUMBER,
    p_id_item NUMBER,
    p_codigo VARCHAR2,
    p_nro_serie VARCHAR2,
    p_estado VARCHAR2,
    p_fecha_proxima_calibracion DATE
) 
AS
BEGIN
    UPDATE UNIDAD_EQUIPO
    SET ID_ITEM = p_id_item,
        CODIGO = p_codigo,
        NRO_SERIE = p_nro_serie,
        ESTADO = p_estado,
