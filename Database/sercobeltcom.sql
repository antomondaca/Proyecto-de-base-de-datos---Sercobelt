CREATE OR REPLACE TRIGGER BITACORA_OT
AFTER INSERT OR UPDATE OR DELETE ON ORDENES_TRABAJO
FOR EACH ROW
DECLARE
    v_id_usuario NUMBER;
    v_identificador VARCHAR2(64);
BEGIN
    -- Flask debe establecer este identificador desde una sesion autenticada.
    v_identificador := SYS_CONTEXT('USERENV', 'CLIENT_IDENTIFIER');
    IF REGEXP_LIKE(v_identificador, '^SERCOBELT:[0-9]{1,38}$') THEN
        SELECT MAX(ID_USUARIO) INTO v_id_usuario
        FROM USUARIOS
        WHERE ID_USUARIO = TO_NUMBER(SUBSTR(v_identificador, 11));
    END IF;
    IF INSERTING THEN
        INSERT INTO BITACORAS (ID_BITACORA, TABLA, OPERACION, ID_REGISTRO, VALOR_ANTERIOR, VALOR_NUEVO, USUARIO_BD, FECHA, ID_USUARIO)
        VALUES (SEQ_BITACORA.NEXTVAL, 'ORDENES_TRABAJO', 'Insert', :NEW.ID_OT, NULL, :NEW.NRO_OT || ' - ' || :NEW.ESTADO, USER, SYSDATE, v_id_usuario);

    ELSIF UPDATING THEN
        INSERT INTO BITACORAS (ID_BITACORA, TABLA, OPERACION, ID_REGISTRO, VALOR_ANTERIOR, VALOR_NUEVO, USUARIO_BD, FECHA, ID_USUARIO)
        VALUES (SEQ_BITACORA.NEXTVAL, 'ORDENES_TRABAJO', 'Update', :NEW.ID_OT, :OLD.ESTADO, :NEW.ESTADO, USER, SYSDATE, v_id_usuario);

    ELSIF DELETING THEN
        INSERT INTO BITACORAS (ID_BITACORA, TABLA, OPERACION, ID_REGISTRO, VALOR_ANTERIOR, VALOR_NUEVO, USUARIO_BD, FECHA, ID_USUARIO)
        VALUES (SEQ_BITACORA.NEXTVAL, 'ORDENES_TRABAJO', 'Delete', :OLD.ID_OT, :OLD.NRO_OT || ' - ' || :OLD.ESTADO, NULL, USER, SYSDATE, v_id_usuario);
    END IF;
END;


